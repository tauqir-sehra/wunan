<h2>Asking for something</h2>
<p>
  If you need something and nobody has listed it, press <a href="/requests/new">Request something</a
  >. Choose what kind of thing it is: something to borrow, something to keep, a trade, or a service.
  Only a short title is needed. You can add more if it helps, like when you need it, your area, or
  how long.
</p>
<p>
  "Needed after" and "Needed by" are both optional. Leave both empty if there's no fixed date. Put
  the same day in both if you need it on one day.
</p>
<p>
  While you type the title, wunan may show offerings that already have what you need. You can open
  one and ask for it straight away. What you typed is kept, so you can come back and post the
  request instead.
</p>

<h2>When someone can help</h2>
<p>
  Other members can press "I can help with this" and choose to help with a new offering made for your
  request, or with an offering they already have. You'll see these under "Offered for this request".
  If you find a matching offering yourself and ask for it, wunan asks whether it's for your
  request. Say yes, and it's offered for your request too.
</p>
<p>
  To go ahead, open one of those offerings and make a proposal, the same as for any offering. It
  starts filled in from your request, and you can change anything. When the person accepts it, your
  request closes by itself. The offering stays up for others, like any other offering.
</p>
<p>
  You can close your request yourself at any time, and open it again later. It never closes because
  it's been quiet.
</p>

<h2>Public messages</h2>
<p>
  Every request and every offering has a short list of public messages. Anyone in wunan can read them
  and write one, for example to ask "Is it brick or plaster?" before offering something. Each
  message can be up to 240 characters.
</p>
<p>
  <strong>Please don't share phone numbers or addresses in public messages.</strong> Once you make a proposal,
  you can talk privately there and share contact details if you both want to.
</p>
<p>
  You can remove your own messages at any time. Nobody else can remove or hide them. If a message
  isn't right, use "Raise an issue" to ask its writer to remove it.
</p>
