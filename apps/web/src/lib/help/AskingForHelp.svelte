<h2>When something goes wrong</h2>
<p>
  If an agreement doesn't work out, for example something lent hasn't come back, you can ask for
  help. Open the agreement in <a href="/agreements">Agreements</a> and press "Ask for help". Describe
  what happened. You'll see what you wrote before you send it.
</p>

<h2>Who helps</h2>
<p>
  The person who invited the other member joins a conversation with you both, to help you find a way
  forward. If they can't help, either of you can ask for more help. Then the next person up the
  invite chain joins, and after that the founding members. That's the last step.
</p>

<h2>What happens next</h2>
<p>
  There is no rush and no deadline. Nobody is removed, blocked or punished: asking for help is about
  talking it through. When it's sorted out, mark it as settled with a short note about what you
  agreed. The note is kept with the agreement.
</p>
