<h2>Searching</h2>
<p>
  Go to <a href="/listings">Find</a> and type what you're looking for, like "ladder" or "rice". Different
  forms of a word are found too, so "apples" also finds "apple".
</p>
<p>
  You can narrow the results by kind (Lend, Gift, Trade, Service) and by area. "Clear filters" shows
  everything again.
</p>
<p>
  Things that are lent out right now are hidden. Tick "Include items currently lent out" to see them
  as well.
</p>

<h2>When you find something</h2>
<p>
  Open the listing and press "Message about this" to talk to the person who listed it. See
  <a href="/help/messages">Messages and contact details</a>.
</p>
