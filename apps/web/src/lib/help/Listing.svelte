<h2>Four kinds of listing</h2>
<ul>
  <li>
    <strong>Lend</strong>: something you want back, like a drill or a tent. You can say how long
    people can keep it.
  </li>
  <li>
    <strong>Gift</strong>: something to give away, like spare food or clothes. You can say how much
    there is, like 5 kg.
  </li>
  <li>
    <strong>Trade</strong>: something you'd swap. List what you'd accept in return, one thing at a
    time with "Add another". List nothing if you're open to offers.
  </li>
  <li>
    <strong>Service</strong>: something you can do, like a haircut or help with forms. You can say
    how long each time is, how many times you offer it, and which days and hours suit you.
  </li>
</ul>

<h2>Making a listing</h2>
<p>
  Go to <a href="/listings/new">New listing</a>. Choose the kind, give it a short title, and add
  anything else that helps, like how to pick it up. Only the title is needed.
</p>
<p>
  You can tick how the handover can happen, like "Picked up from me" or "Online". The area is
  optional; start typing and pick from the suggestions. If people pick up from you, you can use your
  address: others only see its neighbourhood and city until you accept their proposal.
</p>
<p>
  You can add up to 6 photos. wunan removes hidden location details from photos before saving them.
</p>

<h2>Changing a listing</h2>
<p>
  On <a href="/my-listings">My listings</a> you can change a listing, pause it for a while, or remove
  it. A removed listing can be put back later.
</p>
<p>
  Other members can raise a conflict about your listing, for example to ask you to update it. Only
  you see their request, and your listing stays as it is.
</p>
