<h2>Asking for something</h2>
<p>
  On an offering you'd like, press the button for it: "Ask to borrow", "Ask for this", "Offer a
  trade" or "Ask for this service". That makes a <strong>proposal</strong>. You can fill in when,
  how and where, and how much or how long, or leave any of it as "Not decided yet" and write a
  message instead. Only you can change your proposal's details. Whatever it says is what you're
  agreeing to.
</p>

<h2>One page for everything</h2>
<p>
  Each proposal has its own page with the details at the top and your messages below.
  <a href="/proposals">Proposals</a> lists the ones you made and the ones on your offerings. When you're
  both on the page, new messages and changes appear straight away.
</p>

<h2>Accepting</h2>
<p>
  When everything is filled in, the person who listed it can press "Accept". That's it: it's now an
  agreement, and the offering updates by itself. If you change something just before they accept,
  they're shown the new details and asked again.
</p>
<p>
  If someone else's proposal takes everything that's left, other open proposals close, and their
  owners are told. A lent item comes back, so you can still ask to borrow it for other dates. If a
  proposal goes a month without any messages or changes, it closes by itself; you can always make a
  new one.
</p>

<h2>Sharing your phone number or email</h2>
<p>
  Your contact details are private. Save them in <a href="/settings">Settings</a> first. Then, on a proposal
  or agreement, press the "+" beside Send and choose your phone number, your email, or a time to call.
  You see exactly what will be shared. What you choose shows as small labels in the message box and is
  sent with your message. The other person can accept a call time.
</p>

<h2>Places and staying safe</h2>
<p>
  Others only see an offering's neighbourhood and city. The full address shows to the other person
  once their proposal is accepted. Meet in a place you're comfortable with.
</p>
