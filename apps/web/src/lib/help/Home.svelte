<h2>What Home shows</h2>
<p>
  Home lists only what needs you right now. When nothing does, it says "Nothing right now." Press a
  line to go where you can deal with it.
</p>
<ul>
  <li>
    <strong>Arrangements</strong>: the same ones as "Waiting on you" under
    <a href="/arrangements">Arrangements</a>, such as a request you can accept, details to fill in,
    or a new message.
  </li>
  <li>
    <strong>Due back</strong>: something you borrowed or lent that's due back in the next two days,
    with the day and date. If you borrowed it and it's late, it stays here until it's marked
    returned.
  </li>
  <li>
    <strong>Offers on your requests</strong>: someone has offered something for one of your open
    requests.
  </li>
  <li>
    <strong>Asked to change</strong>: someone asked you to change something about one of your
    offerings or requests.
  </li>
</ul>

<h2>When lines go away</h2>
<p>
  Arrangements and things due back go once they no longer need you. Offers and requests to change
  something stay until you press their line on Home, even if you've already seen them somewhere
  else. Something new brings the line back.
</p>
<p>
  To search or browse, use <a href="/offerings">Offerings</a> and <a href="/requests">Requests</a> at
  the top of every page.
</p>
