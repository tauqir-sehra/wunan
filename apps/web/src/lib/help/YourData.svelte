<h2>Downloading your data</h2>
<p>
  In <a href="/settings/export">Settings, Your data</a>, press "Download my data". You get one ZIP
  file with your profile, listings and photos, agreements, messages, and invitations. A README file
  inside explains each part.
</p>

<h2>Who sees what</h2>
<ul>
  <li>Members see your name, your bio, who invited you, who you invited, and your listings.</li>
  <li>Your email address is only for signing in. Nobody else sees it.</li>
  <li>Your phone number and contact email are only shared when you choose to, with one person.</li>
  <li>There are no ads, no tracking, and no counts of views or likes.</li>
</ul>

<h2>Leaving wunan</h2>
<p>
  In <a href="/settings/delete-account">Settings, Leave wunan</a>, you can delete your account with
  your password. Your email, password, contact details, listings and photos are deleted. Your name
  stays, shown as "(no longer a member)", so the people you invited and the agreements you had with
  others still make sense. This can't be undone, so you may want to download your data first.
</p>
