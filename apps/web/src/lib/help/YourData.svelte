<h2>Downloading your data</h2>
<p>
  In <a href="/settings/export">Settings, Your data</a>, press "Download my data". You get one ZIP
  file with your profile, offerings and photos, your arrangements (what was asked, what was agreed,
  and their messages), requests, and invitations. A README file inside explains each part.
</p>

<h2>Who sees what</h2>
<ul>
  <li>Members see your name, your bio, who invited you, who you invited, and your offerings.</li>
  <li>Your email address is only for signing in. Nobody else sees it.</li>
  <li>Your phone number and contact email are only shared when you choose to, with one person.</li>
  <li>
    An offering's area shows only its neighbourhood and city, until you accept someone's proposal.
  </li>
  <li>
    An arrangement's details and messages are seen only by the two of you. If one of you asks for help,
    the helpers see them only if one of you chooses to share them.
  </li>
  <li>
    When you type a place, only what you typed is sent to a place-search service, from the wunan
    server, to suggest places. It never knows who you are.
  </li>
  <li>There are no ads, no tracking, and no counts of views or likes.</li>
</ul>

<h2>Leaving wunan</h2>
<p>
  In <a href="/settings/delete-account">Settings, Leave wunan</a>, you can delete your account with
  your password. Your email, password, contact details, offerings and photos are deleted. Your name
  stays, shown as "(no longer a member)", so the people you invited and the arrangements you had with
  others still make sense. Arrangements you're part of that are still being worked out are closed. This can't be undone, so
  you may want to download your data first.
</p>
