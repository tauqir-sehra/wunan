<h2>Four kinds of offering</h2>
<ul>
  <li>
    <strong>Lend</strong>: something you want back, like a drill or a tent. You can say how long
    people can keep it.
  </li>
  <li>
    <strong>Gift</strong>: something to give away, like spare food or clothes. You can say how much
    there is, like 5 kg.
  </li>
  <li>
    <strong>Trade</strong>: something you'd swap. List what you'd accept in return, one thing at a
    time with "Add another". List nothing if you're open to offers.
  </li>
  <li>
    <strong>Service</strong>: something you can do, like a haircut or help with forms. You can say
    how long each time is, how many times you offer it, and which days and hours suit you.
  </li>
</ul>

<h2>Making an offering</h2>
<p>
  Press <a href="/offerings/new">Offer something</a> at the top of any page. Choose the kind, give it a
  short title, and add anything else that helps, like how to pick it up. Only the title is needed.
</p>
<p>
  You can tick how the handover can happen, like "Picked up from me" or "Online". The area is
  optional; start typing and pick from the suggestions. If people pick up from you, you can use your
  address: others only see its neighbourhood and city until you accept their proposal.
</p>
<p>
  You can add up to 6 photos. wunan removes hidden location details from photos before saving them.
</p>

<h2>Changing an offering</h2>
<p>
  On <a href="/offerings?mine=true">My offerings</a> you can change an offering, pause it for a while, or remove
  it. A removed offering can be put back later.
</p>
<p>
  Other members can raise a conflict about your offering, for example to ask you to update it. Only
  you see their request, and your offering stays as it is.
</p>

<h2>Answering a request</h2>
<p>
  If someone has asked for something you have, open their request on the
  <a href="/requests">Requests</a> page and press "I can help with this". Choose "Make a new
  offering", and the offering form starts filled in from their request. Or choose one of your offerings
  and "Offer this". Your offering then says it fulfils their request, and it stays up like
  any other offering. See <a href="/help/requests">Asking for things</a>.
</p>

<h2>Public messages</h2>
<p>
  Anyone in wunan can write a short public message on your offering, for example to ask a question
  before making a proposal. Please don't share phone numbers or addresses there.
</p>
