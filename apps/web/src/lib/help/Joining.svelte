<h2>Joining</h2>
<p>
  wunan is for people who know each other. You join with an invitation link from someone who is
  already a member. The link works once, for 14 days.
</p>
<p>
  When you open the link, you choose your name and a password. Then we email you a link to confirm
  your email address. Open it within 7 days to finish joining. If the email doesn't arrive, check
  your spam folder, or ask for a new one on the sign-in page.
</p>

<h2>Who invited whom</h2>
<p>
  Your profile shows who invited you, and who you invited. This helps people trust each other. If
  something goes wrong between members, the person who invited them helps to sort it out (see
  <a href="/help/asking-for-help">Asking for help</a>).
</p>

<h2>Inviting someone</h2>
<p>
  Go to <a href="/invitations">Invitations</a> and make a new invitation link. Send the link to the person
  yourself, for example by text message. Only invite people you know and trust. You can cancel a link
  that hasn't been used yet.
</p>
