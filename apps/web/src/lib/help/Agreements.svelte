<h2>Recording what you agreed</h2>
<p>
  When you've agreed to lend, give, trade or offer something, the person who listed it records the
  agreement. Open the listing and press "Record an agreement". Choose who it's with, and how much or
  until when.
</p>
<p>
  The listing updates by itself: a lent item shows as lent out, and gifts show how much is left.
  When nothing is left, the listing closes.
</p>

<h2>Confirming</h2>
<p>
  The other person sees the agreement in <a href="/agreements">Agreements</a> and confirms it. If something
  isn't right, they can say it needs a correction. While it isn't confirmed yet, the person who recorded
  it can cancel it, and the listing goes back to how it was.
</p>

<h2>Loans</h2>
<p>
  A loan has a return date. If the item isn't marked as returned, both people get one gentle
  reminder the day after it was due (if they turned reminders on). When it comes back, the owner
  presses "Mark returned" and the listing is available again.
</p>
