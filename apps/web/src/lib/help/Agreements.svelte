<h2>Agreements</h2>
<p>
  An agreement is made when the person who listed something accepts a proposal. It keeps a copy of
  what was agreed: when, how, where, how much, or how long. Find yours in
  <a href="/agreements">Agreements</a>.
</p>

<h2>Loans</h2>
<p>
  A loan runs from the pickup time for the agreed length. Other people can ask to borrow the same
  thing for other dates. If it isn't marked as returned, both people get one gentle reminder the day
  after it was due (if they turned reminders on). When it's back, the owner presses "Mark returned".
</p>

