<h2>Asking for something</h2>
<p>
  On an offering you'd like, press the button for it: "Ask to borrow", "Ask for this", "Offer a
  trade" or "Ask for this service". That starts an <strong>arrangement</strong> between you and the
  person who listed it. You can fill in when, how and where, and how much or how long, or leave any
  of it as "Not decided yet" and write a message instead. On the arrangement, press "Add" or
  "Change" next to a detail to fill it in right there. Only you can change these details, and
  whatever they say is what you're asking for.
</p>

<h2>One place for each arrangement</h2>
<p>
  Each arrangement has one page, from the first ask to the end. It shows where it stands, what has
  happened so far, the details, what you can do next, and your messages.
  <a href="/arrangements">Arrangements</a> lists all of yours. The ones waiting on you are at the top.
</p>

<h2>Where it stands</h2>
<ul class="list-disc pl-6">
  <li><strong>Being arranged</strong>: you're still working out the details.</li>
  <li><strong>Agreed</strong>: the person who listed it accepted. The details are now fixed.</li>
  <li><strong>On loan</strong>: a lent thing is with the borrower until it's due back.</li>
  <li><strong>Returned</strong>: the owner marked a loan as returned.</li>
  <li><strong>Done</strong>: one of you marked a gift, trade or service as done.</li>
  <li><strong>Ended</strong>: it was declined, withdrawn, or closed.</li>
</ul>

<h2>Agreeing</h2>
<p>
  When everything is filled in, the person who listed it can press "Accept". That's it: you've
  agreed, and the offering updates by itself. If you change something just before they accept,
  they're shown the new details and asked again.
</p>
<p>
  If someone else's arrangement takes everything that's left, other open ones close, and their
  owners are told. A lent item comes back, so you can still ask to borrow it for other dates. If an
  arrangement goes a month without any messages or changes, it closes by itself.
</p>

<h2>Asking again</h2>
<p>
  If an arrangement was declined, withdrawn or closed, you can ask again for the same offering. It
  carries on in the same place, with your earlier messages.
</p>

<h2>Loans and marking things done</h2>
<p>
  A loan runs from the pickup time for the agreed length. If it isn't marked as returned, you both
  get one gentle reminder the day after it was due (if you turned reminders on). When it's back, the
  owner presses "Mark returned".
</p>
<p>
  For a gift, trade or service, either of you can press "Mark as done" once it has happened. It's
  optional, nobody is reminded about it, and you can take it back with "Not done yet".
</p>

<h2>Sharing your phone number or email</h2>
<p>
  Your contact details are private. Save them in <a href="/settings">Settings</a> first. Then, in an
  arrangement, press the "+" beside Send and choose your phone number, your email, or a time to call.
  You see exactly what will be shared. What you choose shows as small labels in the message box and is
  sent with your message. The other person can accept a call time.
</p>

<h2>Places and staying safe</h2>
<p>
  Others only see an offering's neighbourhood and city. The full address shows to the other person
  once you've agreed. Meet in a place you're comfortable with.
</p>

