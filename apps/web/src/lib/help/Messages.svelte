<h2>Messages</h2>
<p>
  Messages are between you and one other member. When you're both on the same conversation, new
  messages appear straight away. <a href="/messages">Messages</a> shows all your conversations, newest
  first, and marks the ones with new messages.
</p>

<h2>Sharing your phone number or email</h2>
<p>
  Your contact details are private. You can save them in <a href="/settings">Settings</a>, and share
  them with one person at a time from a conversation, with "Share contact details". You choose what
  to share and see exactly what they will get before you send it.
</p>

<h2>Arranging a call</h2>
<p>
  In a conversation you can suggest a time to talk. The other person can accept it. Share your phone
  number too if they don't have it yet.
</p>

<h2>Staying safe</h2>
<p>
  Meet in a place you're comfortable with, and only share your address when you're ready. If
  something goes wrong after an agreement, see <a href="/help/asking-for-help">Asking for help</a>.
</p>
